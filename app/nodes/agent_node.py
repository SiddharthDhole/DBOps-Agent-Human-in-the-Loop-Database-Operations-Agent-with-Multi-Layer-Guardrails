from typing import Any, Optional

from langchain_core.messages import SystemMessage, trim_messages
from langchain_core.runnables import RunnableConfig

from app.state import AgentState
from app.model import model_with_tools
from app.prompts import SYSTEM_PROMPT
from app.observability import log_event


def print_agent_context(state: AgentState) -> None:
    print("\nAgent Context:")
    print(f"  sql_query      : {state.get('sql_query')}")
    print(f"  sql_result     : {state.get('sql_result')}")
    print(f"  error          : {state.get('error')}")
    print(f"  retry_count    : {state.get('retry_count', 0)}")


def agent_node(
    state: AgentState,
    config: Optional[RunnableConfig] = None,
) -> dict[str, Any]:

    schema_context = state.get("schema_context", "")

    log_event(
        event="agent_node_invoked",
        node="agent",
        has_schema_context=bool(schema_context),
        retry_count=state.get("retry_count", 0),
    )

    context_message = SystemMessage(
        content=f"""
Relevant database schema:

{schema_context}
"""
    )

    # Sliding Window: Keep recent conversation context (starts on HumanMessage)
    raw_messages = state.get("messages", [])
    trimmed_messages = trim_messages(
        raw_messages,
        max_tokens=8,
        token_counter=len,
        strategy="last",
        start_on="human",
        allow_partial=False,
    )
    if not trimmed_messages and raw_messages:
        trimmed_messages = raw_messages[-6:]

    response = model_with_tools.invoke(
        [
            SystemMessage(content=SYSTEM_PROMPT),
            context_message,
            *trimmed_messages,
        ],
        config=config,
    )

    # Fallback if reasoning model exhausted tokens or returned empty content after tool execution
    if not getattr(response, "content", "").strip() and not response.tool_calls:
        for m in reversed(raw_messages):
            if getattr(m, "type", None) == "tool" or m.__class__.__name__ == "ToolMessage":
                tool_output = str(getattr(m, "content", "")).strip()
                if tool_output and not tool_output.startswith("ERROR") and not tool_output.startswith("SQL_BLOCKED"):
                    response.content = f"Query executed successfully. Result:\n\n{tool_output}"
                    break
        if not getattr(response, "content", "").strip():
            response.content = "Operation completed successfully."

    update: dict[str, Any] = {
        "messages": [response]
    }

    # Capture SQL generated by the LLM
    tool_names = []
    if response.tool_calls:
        for tool_call in response.tool_calls:
            tool_names.append(tool_call.get("name", "unknown"))
            if tool_call.get("name") == "execute_sql":
                update["sql_query"] = tool_call.get("args", {}).get("query")

    log_event(
        event="agent_node_completed",
        node="agent",
        tool_calls=",".join(tool_names) if tool_names else "none",
        sql_query=update.get("sql_query", "none"),
    )

    return update